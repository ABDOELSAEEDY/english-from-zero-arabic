function ErrorComponent({ error, reset }: ErrorComponentProps) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);
  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-bold text-foreground">حصلت مشكلة في تحميل الصفحة</h1>
        <p className="mt-2 text-sm text-muted-foreground">جرّب تاني بعد شوية.</p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="rounded-2xl bg-primary px-5 py-3 font-bold text-primary-foreground"
          >
            حاول تاني
          </button>
          <a href="/" className="rounded-2xl border border-input bg-background px-5 py-3 font-bold text-foreground">
            الرئيسية
          </a>
        </div>
      </div>
    </div>
  );
}

const themeScript = `try{var t=localStorage.getItem('theme');if(t==='dark'||(!t&&matchMedia('(prefers-color-scheme: dark)').matches))document.documentElement.classList.add('dark')}catch(e){}`;

